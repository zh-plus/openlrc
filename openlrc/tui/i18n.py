def normalize_language(value: str) -> str:
    return value if value in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def current_language() -> str:
    app = _active_textual_app()
    if app is None:
        return DEFAULT_LANGUAGE
    return normalize_language(str(getattr(app, "ui_language", DEFAULT_LANGUAGE)))


def _active_textual_app() -> object | None:
    """Return Textual's active App while tolerating private API changes."""

    try:
        from textual._context import active_app
    except ImportError:
        return None
    try:
        return active_app.get()
    except LookupError:
        return None


def tr(text: str, *, language: str | None = None) -> str:
    """Translate TUI-owned copy while leaving backend/model diagnostics intact."""

    selected_language = normalize_language(language or current_language())
    if selected_language != "zh-cn" or not text:
        return text
    translated = ZH_CN.get(text)
    if translated is not None:
        return translated
    if "\n" in text:
        return "\n".join(tr(line, language=selected_language) for line in text.split("\n"))
    for prefix, localized_prefix in _PREFIXES.items():
        if text.startswith(prefix):
            return localized_prefix + tr(text[len(prefix) :], language=selected_language)
    if " · " in text:
        return " · ".join(tr(part, language=selected_language) for part in text.split(" · "))
    for pattern, replacement in _VALIDATION_PATTERNS:
        if pattern.fullmatch(text):
            return pattern.sub(replacement, text)
    for pattern, replacement in _COUNT_PATTERNS:
        if pattern.fullmatch(text):
            return pattern.sub(replacement, text)
    return text
